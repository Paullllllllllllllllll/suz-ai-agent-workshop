"""Turn an approved curation plan into a reviewable Zotero Run-JavaScript snippet.

The generated script uses the real Zotero JavaScript API only -- ``setType``,
``setField``, ``saveTx``, ``Zotero.Items.merge``, ``new Zotero.Item``,
``Zotero.Attachments.linkFromFile`` -- so every write goes through Zotero's
validation, versioning, full-text, and relation logic (merges keep citation-key
redirects). No SQL is touched. The user reviews the embedded ``PLAN`` and pastes
the snippet into Tools -> Developer -> Run JavaScript with "Run as async
function" enabled.

An action covers three missions through one apply path: deduplication (a
non-empty ``merge``), metadata repair (``field_fixes`` / ``creators``), and
tagging (``add_tags`` / ``clear_auto_tags`` / ``remove_tags``, Mode C). All keys
are optional; an action with only ``add_tags`` + ``clear_auto_tags`` simply
re-tags one record. A fourth mission, import/accession (Mode D), rides the same
snippet through a top-level ``creates`` array, independent of ``actions``: each
entry creates a new item and links a moved PDF as a linked-file attachment.

Plan schema (JSON)::

    {
      "actions": [
        {
          "keep": "ABCD1234",                  # Zotero item key to keep / edit (master)
          "merge": ["EFGH5678", "IJKL9012"],   # optional: keys merged into the master
          "field_fixes": {                      # optional, applied to the master
            "itemType": "book",                 # optional type change
            "date": "1982",                     # any Zotero field name -> value
            "publisher": "..."
          },
          "creators": [                          # optional: REPLACES the creator list
            {"creatorType": "author", "firstName": "Pierre", "lastName": "Bourdieu"},
            {"creatorType": "author", "name": "Royal Society"}   # corporate (single-field)
          ],
          "clear_auto_tags": true,               # optional: remove all type=1 (automatic) tags
          "remove_tags": ["old-tag"],            # optional: remove these tags by name
          "add_tags": ["topic::inequality", "region::europe"]  # optional: add as manual (type 0) tags
        }
      ],
      "creates": [                              # optional (Mode D import); independent of actions
        {
          "itemType": "journalArticle",        # new item's Zotero type (default "document")
          "fields": {"title": "...", "date": "1990"},   # Zotero field name -> value
          "creators": [                          # same shape as an action's creators
            {"creatorType": "author", "firstName": "Jane", "lastName": "Doe"}
          ],
          "add_tags": ["topic::migration"],     # optional manual (type 0) tags
          "path": "/path/to/Literature/Doe 1990 Migration.pdf"  # PDF to attach as a LINKED file
        }
      ]
    }

Usage::

    python scripts/build_runjs.py plan.json --out apply_dedup.js
    python scripts/build_runjs.py plan.json        # writes to stdout
"""

from __future__ import annotations

import argparse
import json
import sys

_TEMPLATE = """\
// ---------------------------------------------------------------------------
// Zotero curation apply script (generated by the zotero-curator skill).
// Review PLAN below, then run via Tools -> Developer -> Run JavaScript
// with "Run as async function" checked. BACK UP zotero.sqlite + storage/ first.
// Every write goes through the Zotero API; no SQL is touched. Merges are not
// undoable.
// ---------------------------------------------------------------------------

const PLAN = %s;

const lib = Zotero.Libraries.userLibraryID;
const results = [];

async function getItem(key) {
  return await Zotero.Items.getByLibraryAndKeyAsync(lib, key);
}

function mapCreator(c) {
  const out = { creatorTypeID: Zotero.CreatorTypes.getID(c.creatorType || "author") };
  if (c.name) {
    out.name = c.name;
    out.fieldMode = 1;
  } else {
    out.firstName = c.firstName || "";
    out.lastName = c.lastName || "";
    out.fieldMode = 0;
  }
  return out;
}

for (const action of (PLAN.actions || [])) {
  const log = { keep: action.keep, merged: [], typeChanged: null, fieldsSet: [], creatorsSet: false, autoTagsCleared: [], tagsRemoved: [], tagsAdded: [], skipped: [] };
  const keep = await getItem(action.keep);
  if (!keep) {
    log.skipped.push("keeper " + action.keep + " not found");
    results.push(log);
    continue;
  }

  // --- field fixes on the keeper ---
  const fixes = action.field_fixes || {};
  if (fixes.itemType) {
    try {
      keep.setType(Zotero.ItemTypes.getID(fixes.itemType));
      log.typeChanged = fixes.itemType;
    } catch (e) {
      log.skipped.push("setType " + fixes.itemType + ": " + e);
    }
  }
  for (const [field, value] of Object.entries(fixes)) {
    if (field === "itemType") continue;
    try {
      keep.setField(field, value);
      log.fieldsSet.push(field);
    } catch (e) {
      log.skipped.push("setField " + field + ": " + e);
    }
  }
  // --- creator replacement on the keeper ---
  if (Array.isArray(action.creators) && action.creators.length) {
    try {
      keep.setCreators(action.creators.map(mapCreator));
      log.creatorsSet = true;
    } catch (e) {
      log.skipped.push("setCreators: " + e);
    }
  }

  // --- tags: clear existing automatic (type=1) import tags ---
  if (action.clear_auto_tags) {
    for (const t of keep.getTags()) {
      if (t.type === 1) {
        keep.removeTag(t.tag);
        log.autoTagsCleared.push(t.tag);
      }
    }
  }
  // --- tags: remove specific tags by name ---
  for (const tg of (action.remove_tags || [])) {
    keep.removeTag(tg);
    log.tagsRemoved.push(tg);
  }
  // --- tags: add manual (type 0) tags (idempotent; Zotero dedupes) ---
  for (const tg of (action.add_tags || [])) {
    keep.addTag(tg, 0);
    log.tagsAdded.push(tg);
  }

  if (log.typeChanged || log.fieldsSet.length || log.creatorsSet
      || log.autoTagsCleared.length || log.tagsRemoved.length || log.tagsAdded.length) {
    await keep.saveTx();
  }

  // --- merge duplicates into the keeper ---
  const others = [];
  for (const key of (action.merge || [])) {
    const it = await getItem(key);
    if (it) {
      others.push(it);
      log.merged.push(key);
    } else {
      log.skipped.push("merge target " + key + " not found");
    }
  }
  if (others.length) {
    await Zotero.Items.merge(keep, others);
  }

  // --- detach mis-attached / redundant attachment items (linked files stay on disk) ---
  log.detached = [];
  for (const attKey of (action.detach || [])) {
    const att = await getItem(attKey);
    if (!att) {
      log.skipped.push("detach " + attKey + " not found");
      continue;
    }
    if (!att.isAttachment()) {
      log.skipped.push("detach " + attKey + " is not an attachment");
      continue;
    }
    if (att.attachmentLinkMode !== Zotero.Attachments.LINK_MODE_LINKED_FILE) {
      log.skipped.push("detach " + attKey + " is not a linked file; left in place");
      continue;
    }
    await att.eraseTx();
    log.detached.push(attKey);
  }

  // --- relink linked-file attachments to renamed paths ---
  log.relinked = [];
  for (const rl of (action.relink || [])) {
    const att = await getItem(rl.att);
    if (!att) {
      log.skipped.push("relink " + rl.att + " not found");
      continue;
    }
    try {
      att.attachmentPath = rl.path;
      if (rl.title) att.setField("title", rl.title);
      await att.saveTx();
      log.relinked.push(rl.att);
    } catch (e) {
      log.skipped.push("relink " + rl.att + ": " + e);
    }
  }

  results.push(log);
}

// --- create new items from loose PDFs (Mode D import) + link the moved file ---
const createLog = [];
for (const c of (PLAN.creates || [])) {
  const clog = { itemType: c.itemType || "document", key: null, fieldsSet: [], creatorsSet: false, tagsAdded: [], linked: false, skipped: [] };
  let item;
  try {
    item = new Zotero.Item(c.itemType || "document");
    item.libraryID = lib;
  } catch (e) {
    clog.skipped.push("new Item " + (c.itemType || "document") + ": " + e);
    createLog.push(clog);
    continue;
  }
  for (const [field, value] of Object.entries(c.fields || {})) {
    if (field === "itemType") continue;
    try {
      item.setField(field, value);
      clog.fieldsSet.push(field);
    } catch (e) {
      clog.skipped.push("setField " + field + ": " + e);
    }
  }
  if (Array.isArray(c.creators) && c.creators.length) {
    try {
      item.setCreators(c.creators.map(mapCreator));
      clog.creatorsSet = true;
    } catch (e) {
      clog.skipped.push("setCreators: " + e);
    }
  }
  for (const tg of (c.add_tags || [])) {
    item.addTag(tg, 0);
    clog.tagsAdded.push(tg);
  }
  const itemID = await item.saveTx();
  clog.key = item.key;
  // attach the moved PDF as a LINKED file (kept in the library folder, not
  // copied into storage/); requires Zotero's linked-attachment base directory.
  if (c.path) {
    try {
      await Zotero.Attachments.linkFromFile({
        file: Zotero.File.pathToFile(c.path),
        parentItemID: itemID,
      });
      clog.linked = true;
    } catch (e) {
      clog.skipped.push("linkFromFile " + c.path + ": " + e);
    }
  }
  createLog.push(clog);
}
if ((PLAN.creates || []).length) {
  results.push({ created: createLog });
}

// --- remove records entirely (policy removals; children erased with them) ---
const removalLog = [];
for (const key of (PLAN.removals || [])) {
  const it = await getItem(key);
  if (!it) {
    removalLog.push(key + ": not found (already removed?)");
    continue;
  }
  await it.eraseTx();
  removalLog.push(key + ": erased");
}
results.push({ removals: removalLog });

return JSON.stringify(results, null, 2);
"""


def build_script(plan: dict) -> str:
    has_actions = isinstance(plan.get("actions"), list)
    has_creates = isinstance(plan.get("creates"), list)
    if not has_actions and not has_creates:
        raise ValueError("plan must have an 'actions' or 'creates' array")
    return _TEMPLATE % json.dumps(plan, ensure_ascii=False, indent=2)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate a Zotero curation Run-JS snippet."
    )
    parser.add_argument("plan", help="path to the approved plan JSON")
    parser.add_argument("--out", default="", help="output .js path (default stdout)")
    args = parser.parse_args(argv)

    with open(args.plan, encoding="utf-8") as fh:
        plan = json.load(fh)

    try:
        script = build_script(plan)
    except ValueError as exc:
        sys.stderr.write(f"error: {exc}\n")
        return 2

    if args.out:
        with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(script)
        n_act = len(plan.get("actions") or [])
        n_new = len(plan.get("creates") or [])
        sys.stderr.write(
            f"Wrote Run-JS snippet ({n_act} action(s), {n_new} create(s)) to {args.out}\n"
        )
    else:
        sys.stdout.write(script)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
